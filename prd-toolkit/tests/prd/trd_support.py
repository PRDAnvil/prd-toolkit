"""Shared helper of the trd characterization tests (testing.md: Harness, Setup steps; test-cases/trd.yaml header).

Everything here comes from docs/prd/prd-toolkit/testing.md and the header of test-cases/trd.yaml: the scratch
repository the steps V0 to VR build in a test's tmp_path, the environment every run, every step's command and the
test's own git commands use, the way a run's text becomes an argument list, and the assertion keys
`stdout_first_line`, `pack_part_titles` and `pack_part_lines`.

The borrowed steps N0 and N0X are imported from status_next_support (testing.md, Borrowed steps and helpers);
every other helper is defined here. A step that cannot be applied (a command that exits other than 0, a line it
changes that is not there) raises StepError inside the `trd_repo` fixture, so the test ends as an error, not a
failure.
"""
from __future__ import annotations

import os
import shlex
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

import pytest

from status_next_support import N0, N0X

REPO = Path(__file__).resolve().parents[3]  # tests/prd/<file> -> tests -> prd-toolkit -> the repository root
TRD = REPO / "prd-toolkit" / "scripts" / "prd_trd.py"
ORDERS_REL = Path("docs") / "prd" / "orders"

# testing.md, Subprocess environment; test-cases/trd.yaml header: the variables a run never inherits.
_DROPPED_ENV = (
    "PYTHONIOENCODING", "PYTHONPATH", "PYTHONHOME", "PRD_LINT_CI", "PRD_HELP_FILE",
    "GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE", "GIT_COMMON_DIR", "PRD_PLUGINS_FILE",
)
RUN_TIMEOUT = 300  # seconds; a harness choice, so a hung script ends the test


class StepError(Exception):
    """A step could not be applied: the case's state was never built, so the test ends as an error."""


@dataclass
class Result:
    exit: int
    stdout: bytes
    stderr: bytes

    @property
    def out(self) -> str:
        return self.stdout.decode("utf-8")

    @property
    def err(self) -> str:
        return self.stderr.decode("utf-8")


def trd_env() -> dict[str, str]:
    """The environment of every run, step command and test git command (GIT_CONFIG_* come from the process)."""
    env = dict(os.environ)
    for name in _DROPPED_ENV:
        env.pop(name, None)
    env["GIT_CONFIG_GLOBAL"] = "/dev/null"
    env["GIT_CONFIG_NOSYSTEM"] = "1"
    return env


def orders(tmp: Path) -> Path:
    """ORDERS = <tmp>/docs/prd/orders."""
    return tmp / ORDERS_REL


def argv(text: str, tmp: Path) -> list[str]:
    """A run's text as its argument list (trd.yaml header): TRD and <tmp> replaced, shlex-split, python -> sys.executable."""
    words = shlex.split(text.replace("TRD", str(TRD)).replace("<tmp>", str(tmp)))
    if words and words[0] == "python":
        words[0] = sys.executable
    return words


def run(tmp: Path, text: str) -> Result:
    """Run one case's command text with <tmp> as the working directory, no shell; stdout and stderr as bytes."""
    proc = subprocess.run(argv(text, tmp), cwd=tmp, env=trd_env(), capture_output=True, timeout=RUN_TIMEOUT)
    return Result(proc.returncode, proc.stdout, proc.stderr)


def git(cwd: Path, *args: str) -> subprocess.CompletedProcess:
    """A git command with the trd environment (a test's own git commands and the steps' ones)."""
    return subprocess.run(["git", *args], cwd=cwd, env=trd_env(), capture_output=True, timeout=RUN_TIMEOUT)


def sha7(tmp: Path) -> str:
    """The first 7 characters of what `git rev-parse HEAD` prints in <tmp>."""
    proc = git(tmp, "rev-parse", "HEAD")
    assert proc.returncode == 0, f"git rev-parse HEAD exited {proc.returncode}: {proc.stderr!r}"
    return proc.stdout.decode("utf-8").strip()[:7]


def gen_line(tmp: Path) -> str:
    """GEN of the trd.yaml header, with <sha7> put in."""
    return ("Generated by prd trd from `docs/prd/orders` at " + sha7(tmp)
            + ". Do not edit it: run prd trd again. The PRD is the authority,"
            + " and the black-box tester never reads this file.")


# -- assertion keys (testing.md, Harness, Assertions) --

def stdout_first_line(stdout: str) -> str:
    lines = stdout.splitlines()
    assert lines, "stdout is empty"
    return lines[0]


def pack_part_titles(stdout: str) -> list[str]:
    """The stdout lines that start with `## `, in order."""
    return [line for line in stdout.splitlines() if line.startswith("## ")]


def pack_part_lines(stdout: str, title: str) -> list[str]:
    """The lines from `## <title>` (exactly once in stdout) up to, not including, the next `## ` line or the end."""
    lines = stdout.splitlines()
    heading = f"## {title}"
    hits = [i for i, line in enumerate(lines) if line == heading]
    assert len(hits) == 1, f"stdout holds the line {heading!r} {len(hits)} times, not once:\n{stdout}"
    start = hits[0]
    end = next((j for j in range(start + 1, len(lines)) if lines[j].startswith("## ")), len(lines))
    return lines[start:end]


def with_sha7(lines: list[str], tmp: Path) -> list[str]:
    value = sha7(tmp)
    return [line.replace("<sha7>", value) for line in lines]


def stderr_single_line_starts(stderr: str, text: str) -> None:
    lines = stderr.splitlines()
    assert len(lines) == 1, f"stderr does not hold exactly one line: {stderr!r}"
    assert lines[0].startswith(text), f"stderr line {lines[0]!r} does not start with {text!r}"


def snapshot(folder: Path) -> dict[str, bytes]:
    """Every file under `folder`, by relative path, with its bytes."""
    return {str(p.relative_to(folder)): p.read_bytes() for p in sorted(folder.rglob("*")) if p.is_file()}


def porcelain_lines(tmp: Path) -> list[str]:
    proc = git(tmp, "status", "--porcelain")
    assert proc.returncode == 0, f"git status --porcelain exited {proc.returncode}: {proc.stderr!r}"
    return proc.stdout.decode("utf-8").splitlines()


# -- steps (test-cases/trd.yaml header) --

def _write(path: Path, lines: list[str]) -> None:
    """Write the lines, each ending in a newline, creating the parent folders."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes("".join(line + "\n" for line in lines).encode("utf-8"))


def _step_git(cwd: Path, *args: str) -> None:
    proc = git(cwd, *args)
    if proc.returncode != 0:
        raise StepError(f"git {' '.join(args)} exited {proc.returncode} in {cwd}: "
                        f"{proc.stderr.decode('utf-8', 'replace')}")


def _commit(root: Path, message: str) -> None:
    _step_git(root, "add", "-A")
    _step_git(root, "commit", "-q", "-m", message)


def _read_lines(path: Path) -> list[str]:
    return path.read_text(encoding="utf-8").split("\n")


def _write_lines(path: Path, lines: list[str]) -> None:
    path.write_bytes("\n".join(lines).encode("utf-8"))


def _one(lines: list[str], start: int, end: int, line: str, path: Path) -> int:
    hits = [i for i in range(start, end) if lines[i] == line]
    if len(hits) != 1:
        raise StepError(f"{path}: expected the line {line!r} once, found it {len(hits)} times")
    return hits[0]


def V0(tmp: Path) -> None:
    N0(tmp)
    _step_git(tmp, "config", "user.name", "Sample")
    _step_git(tmp, "config", "user.email", "sample@example.com")
    _step_git(tmp, "config", "commit.gpgsign", "false")
    _step_git(tmp, "config", "core.hooksPath", "/dev/null")
    _commit(tmp, "base")


def VA(tmp: Path) -> None:
    prd_md = orders(tmp) / "prd.md"
    lines = _read_lines(prd_md)
    heading = "## 8. Adoption map"
    start = _one(lines, 0, len(lines), heading, prd_md) + 1
    end = next((j for j in range(start, len(lines)) if lines[j].startswith("## ")), len(lines))
    i = _one(lines, start, end, "Not applicable: new project.", prd_md)
    lines[i] = "See adoption.md."
    _write_lines(prd_md, lines)
    _write(orders(tmp) / "adoption.md", [
        "# Adoption map",
        "",
        "| Area | State | Boundary |",
        "|---|---|---|",
        "| import | adopted | `src/importer.py`, `src/lib/**` |",
        "| reports | not started | `src/reports.py` |",
        "| billing | not started | `src/billing/*.py` |",
    ])
    for rel in ("src/importer.py", "src/lib/a.py", "src/lib/sub/b.py", "src/reports.py", "src/billing/pay.py",
                "src/billing/deep/x.py", "notes/readme.md", ".prd-toolkit/x.py", ".prd-toolkit-notes.md"):
        _write(tmp / rel, ["x = 1"])
    _commit(tmp, "map")


def VS(tmp: Path) -> None:
    path = orders(tmp) / "features" / "import.md"
    for after, new in (("Status: built", "Source: src/importer.py:1 @abc1234"),
                       ("Status: verified", "Source: src/gone.py:4 @abc1234"),
                       ("Status: live (since 1.0.0)", "Source: src/importer.py:5 @abc1234")):
        lines = _read_lines(path)
        i = _one(lines, 0, len(lines), after, path)
        lines.insert(i + 1, new)
        _write_lines(path, lines)
    _commit(tmp, "sources")


def VW(tmp: Path) -> None:
    _write(tmp / "src" / "untracked.py", ["x = 1"])


def VO(tmp: Path) -> None:
    _write(tmp / "view.md", ["old text"])


def VL(tmp: Path) -> None:
    os.symlink(str(orders(tmp).absolute()), tmp / "link")


def VE(tmp: Path) -> None:
    (tmp / "empty").mkdir()


def VX(tmp: Path) -> None:
    folder = tmp / "nogit"
    folder.mkdir()
    N0X(folder)


def VN(tmp: Path) -> None:
    folder = tmp / "nocommit"
    folder.mkdir()
    N0(folder)


def VR(tmp: Path) -> None:
    folder = tmp / "repo"
    folder.mkdir()
    V0(folder)


STEPS = {"V0": V0, "VA": VA, "VS": VS, "VW": VW, "VO": VO, "VL": VL, "VE": VE, "VX": VX, "VN": VN, "VR": VR}


@pytest.fixture
def trd_repo(request, tmp_path, monkeypatch) -> Path:
    """<tmp>, built by the case's steps in the order it lists them, after GIT_CONFIG_* are set in the process."""
    monkeypatch.setenv("GIT_CONFIG_GLOBAL", "/dev/null")
    monkeypatch.setenv("GIT_CONFIG_NOSYSTEM", "1")
    for step in request.param:
        STEPS[step](tmp_path)
    return tmp_path


def given_steps(*steps: str):
    """Mark a test with its case's `setup:` list; the `trd_repo` fixture runs the steps."""
    return pytest.mark.parametrize("trd_repo", [steps], indirect=True, ids=["+".join(steps)])
