@given(setup_116_3)
def test_gitlab_setup_commands(built):
    """@prd T-116.3"""
    tmp = built
    r1 = run(tmp, tmp / "a", "python HOOKS ci --gitlab docs/prd/orders")
    r2 = run(tmp, tmp / "b", "python HOOKS ci --gitlab docs/prd/orders")
    assert r1.exit == 0, r1.stdout + r1.stderr
    assert r2.exit == 0, r2.stdout + r2.stderr
    setup_lines = ['    - "touch ~/.npmrc"', '    - "mkdir -p .cache"']

    assert_lines(tmp / "a" / GL_FILE, with_lines_after(lines_116_1(), PIP_UV, setup_lines))

    expected = [
        "test-deploy-staging:",
        "  image: python:3.12",
        "  rules:",
        "    - when: manual",
        "  allow_failure: true",
        "  before_script:",
        '    - "pip install uv"',
        '    - "touch ~/.npmrc"',
        '    - "mkdir -p .cache"',
        "  script:",
        '    - "export PRD_ENV=staging TEST_ENV=staging; pytest tests/system"',
    ]
    lines = file_lines(tmp / "b" / GL_FILE)
    assert in_relative_order(lines, expected), "\n".join(lines)
    # the case's note: the lines are consecutive, and they are the last lines of the file; the file holds six
    # '    - "pip install uv"' lines, and each is directly followed by the two setup lines, in that order
    assert lines[-len(expected):] == expected, "\n".join(lines)
    at = [i for i, line in enumerate(lines) if line == PIP_UV]
    assert len(at) == 6, "\n".join(lines)
    for i in at:
        assert lines[i + 1:i + 3] == setup_lines, (i, lines[i:i + 3])


